export function icon(name, sizeClass = '') {
  const svg = ICONS[name] || ICONS.bag;
  const cls = sizeClass ? ` class="${sizeClass}"` : '';
  return svg.replace('<svg', `<svg${cls}`);
}

export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function initials(name) {
  return String(name || '').split(/\s+/).map((w) => w[0]).slice(0, 2).join('').toUpperCase() || '?';
}

export function toast(message, type = '') {
  let el = document.querySelector('.owner-toast');
  if (!el) {
    el = document.createElement('div');
    document.body.appendChild(el);
  }
  clearTimeout(el._hideTimer);
  el.className = `owner-toast ${type}`;
  el.textContent = message;
  el._hideTimer = setTimeout(() => { if (el.parentNode) el.remove(); }, 4000);
}

export function confirmDialog(message, onConfirm, onCancel) {
  const destructive = /delete|clear|remove|erase|hata|mita|khatam|barbad/i.test(message);
  const backdrop = openModal({
    title: 'Please confirm',
    body: `<p style="margin:0;font-size:13.5px;line-height:1.6;color:#334155">${esc(message)}</p>`,
    footer: `<button class="btn btn-ghost" data-no>Cancel</button>
             <button class="btn ${destructive ? 'btn-danger' : 'btn-primary'}" data-yes>${destructive ? 'Delete' : 'Confirm'}</button>`,
    onMount: (bd) => {
      bd.querySelector('[data-no]').addEventListener('click', () => {
        bd.remove();
        if (onCancel) onCancel();
      });
      bd.querySelector('[data-yes]').addEventListener('click', () => {
        bd.remove();
        if (onConfirm) onConfirm();
      });
    },
  });
  return backdrop;
}

export function openModal({ title, subtitle, body, footer, onMount }) {
  const backdrop = document.createElement('div');
  backdrop.className = 'owner-modal-backdrop';
  backdrop.innerHTML = `
    <div class="owner-modal">
      <div class="owner-modal-head">
        <div>
          <h2>${esc(title || '')}</h2>
          ${subtitle ? `<p>${esc(subtitle)}</p>` : ''}
        </div>
        <button class="owner-modal-close" data-close>×</button>
      </div>
      <div class="owner-modal-body">${body}</div>
      ${footer ? `<div class="owner-modal-actions">${footer}</div>` : ''}
    </div>`;
  document.body.appendChild(backdrop);
  linkLabels(backdrop);
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  const close = () => {
    document.removeEventListener('keydown', onKey);
    if (backdrop.parentNode) backdrop.remove();
  };
  backdrop.querySelector('[data-close]').addEventListener('click', close);
  backdrop.querySelectorAll('[data-modal-close]').forEach((btn) => btn.addEventListener('click', close));
  backdrop.addEventListener('click', (e) => { if (e.target === backdrop) close(); });
  document.addEventListener('keydown', onKey);
  if (onMount) onMount(backdrop);
  return backdrop;
}

export function linkLabels(scope = document) {
  scope.querySelectorAll('label').forEach((label) => {
    if (label.htmlFor) return;
    if (label.querySelector('input, select, textarea')) return;
    let el = label.nextElementSibling;
    while (el && !['INPUT', 'SELECT', 'TEXTAREA'].includes(el.tagName)) el = el.nextElementSibling;
    if (!el) return;
    if (!el.id) el.id = 'mz_fld_' + Math.random().toString(36).slice(2, 9);
    label.htmlFor = el.id;
  });
}

export function downloadFile(name, content, mime = 'application/json') {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function emptyState(msg) {
  return `<div class="empty-state">${esc(msg)}</div>`;
}

export function closeModal() {
  const backdrop = document.querySelector('.owner-modal-backdrop');
  if (backdrop && backdrop.parentNode) backdrop.parentNode.removeChild(backdrop);
}
